/**
 * The runtime shared by the generated status extensions of the pi family —
 * omp (`src/shared/omp-status-extension.ts`) and plain pi
 * (`src/shared/pi-status-extension.ts`). Both CLIs load a TypeScript module
 * in-process and hand it every event; what differs is only which events exist,
 * so each harness supplies its own `pi.on(...)` wiring and this file owns the
 * rest: the `DEV3_TASK_ID` guard, the serialized report queue, the throttle and
 * the atomic write.
 */

import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { resolveDev3Home } from "./dev3-home";
import { type Dev3CliLookup, resolveDev3CliPath } from "./dev3-cli-path";

export type StatusExtensionHarness = "omp" | "pi";

/** Where a harness's extension is written: `<dev3 home>/data/agent-hooks/<basename>`. */
export function statusExtensionPath(basename: string, dev3Home: string = resolveDev3Home()): string {
	return `${dev3Home}/data/agent-hooks/${basename}`;
}

/**
 * The dev3 CLI as the extension spawns it: an absolute path, because the
 * module runs inside the agent's own process with no shell to expand `~`.
 * POSIX gets `<dev3 home>/bin/dev3`, where the app installs the binary; Windows
 * the same lookup the generated hook commands use.
 */
export function statusExtensionHookCli(lookup: Dev3CliLookup = {}): string {
	const platform = lookup.platform ?? process.platform;
	if (platform === "win32") return resolveDev3CliPath({ ...lookup, platform });
	return `${resolveDev3Home()}/bin/dev3`;
}

/**
 * The whole module: the shared runtime with `wiring` (the harness's own
 * `pi.on(...)` handlers, tab-indented) spliced in. Handlers may call
 * `report`, `reportWorking`, `reportIdle` and `sessionIdOf`.
 *
 * Reports are queued one after another, because two concurrent dev3 processes
 * could land a tool's "done" after the agent's "stopped" and strand the task
 * in-progress. While the agent is already known to be working, tool events are
 * re-sent only every `WORKING_REFRESH_MS`, so a long tool-heavy turn costs a
 * handful of processes instead of hundreds.
 */
export function buildStatusExtensionModule(spec: { harness: StatusExtensionHarness; cli: string; wiring: string }): string {
	const cli = JSON.stringify(spec.cli);
	const h = spec.harness;
	return `// Generated by dev3 — do not edit. Rewritten before every ${h} launch.
// Reports this ${h} session's lifecycle to the dev3 board through \`dev3 hook ${h}\`
// so the task follows the agent between columns without manual \`dev3 task move\` calls.
import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";

const DEV3_CLI = ${cli};
const HOOK_ARGS = ["hook", "${h}"];
const WORKING_REFRESH_MS = 10_000;
const HOOK_TIMEOUT_MS = 8_000;

type Ctx = { cwd?: string; sessionManager?: { getSessionId?: () => string } };
type Payload = { event: string; sessionId?: string; prompt?: string; submissionId?: string };

export default function dev3StatusHooks(pi: any): void {
	// Only a pane dev3 launched carries DEV3_TASK_ID; anywhere else this module is inert.
	if (!process.env.DEV3_TASK_ID) return;

	let queue: Promise<void> = Promise.resolve();
	let working = false;
	let lastWorkingAt = 0;

	const warn = (text: string): void => {
		try {
			pi.logger?.warn?.(\`dev3 status hook: \${text}\`);
		} catch {}
	};

	const sessionIdOf = (ctx: Ctx | undefined): string | undefined => {
		try {
			const id = ctx?.sessionManager?.getSessionId?.();
			return typeof id === "string" && id ? id : undefined;
		} catch {
			return undefined;
		}
	};

	const deliver = (payload: Payload, cwd: string): Promise<void> =>
		new Promise((resolve) => {
			let child: ReturnType<typeof spawn>;
			try {
				child = spawn(DEV3_CLI, HOOK_ARGS, { cwd, stdio: ["pipe", "ignore", "pipe"], windowsHide: true });
			} catch (err) {
				warn(String(err));
				resolve();
				return;
			}
			let stderr = "";
			const timer = setTimeout(() => {
				try { child.kill(); } catch {}
			}, HOOK_TIMEOUT_MS);
			child.stderr?.on("data", (chunk) => { stderr += String(chunk); });
			child.on("error", (err) => warn(String(err)));
			child.on("close", () => {
				clearTimeout(timer);
				if (stderr.trim()) warn(stderr.trim());
				resolve();
			});
			child.stdin?.on("error", () => {});
			child.stdin?.end(JSON.stringify(payload));
		});

	const report = (ctx: Ctx | undefined, event: string, extra?: Partial<Payload>): void => {
		const sessionId = sessionIdOf(ctx);
		const payload: Payload = { event, ...(sessionId ? { sessionId } : {}), ...extra };
		const cwd = typeof ctx?.cwd === "string" && ctx.cwd ? ctx.cwd : process.cwd();
		// Strictly in event order, one dev3 process at a time (see the header).
		queue = queue.then(() => deliver(payload, cwd));
	};

	const reportWorking = (ctx: Ctx | undefined, event: string, extra?: Partial<Payload>): void => {
		const now = Date.now();
		if (working && !extra && now - lastWorkingAt < WORKING_REFRESH_MS) return;
		working = true;
		lastWorkingAt = now;
		report(ctx, event, extra);
	};

	const reportIdle = (ctx: Ctx | undefined, event: string): void => {
		working = false;
		report(ctx, event);
	};

${spec.wiring}}
`;
}

/**
 * Write a generated extension and return its path. Skipped when the file
 * already holds the same body; otherwise written through a temp name in the
 * same directory, because the reader is another process — an agent that is
 * starting must see the old module or the new one, never a half-written file.
 *
 * Throws when it cannot be written: a launch without the flag is the honest
 * outcome, and the caller logs it.
 */
export function writeStatusExtensionFile(path: string, body: string): string {
	const dir = path.slice(0, path.lastIndexOf("/"));
	mkdirSync(dir, { recursive: true });
	if (existsSync(path) && readFileSync(path, "utf-8") === body) return path;
	const temp = `${path}.${process.pid}.tmp`;
	try {
		writeFileSync(temp, body, "utf-8");
		renameSync(temp, path);
	} catch (err) {
		rmSync(temp, { force: true });
		throw err;
	}
	return path;
}
