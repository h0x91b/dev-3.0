/**
 * The pi extension dev3's in-app sign-in loads (`pi -e <path>`). pi has no
 * `login` subcommand, and a `/login` given as an argument reaches the model as
 * a prompt, so the command is typed into pi's editor instead and waits for the
 * user's Enter. An older pi without `setEditorText` just shows an empty editor.
 */

import { statusExtensionPath, writeStatusExtensionFile } from "./status-extension-core";

export const PI_LOGIN_EXTENSION_BASENAME = "pi-login.ts";

export function buildPiLoginExtension(): string {
	return `// Generated by dev3 — do not edit. Loaded only by dev3's account sign-in terminal.
// Types /login into pi's editor; nothing is submitted until the user presses Enter.
export default function (pi: any) {
	pi.on("session_start", (_event: unknown, ctx: any) => {
		if (ctx?.hasUI === false) return;
		ctx?.ui?.setEditorText?.("/login");
	});
}
`;
}

/** Write the extension and return its path (atomic, skipped when unchanged). */
export function writePiLoginExtension(dev3Home?: string): string {
	return writeStatusExtensionFile(statusExtensionPath(PI_LOGIN_EXTENSION_BASENAME, dev3Home), buildPiLoginExtension());
}
